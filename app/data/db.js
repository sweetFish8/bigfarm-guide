// ============ ヘルパー ============
export function getFarm(slug) {
  return farms.find((f) => f.slug === slug);
}

export function getFarmCategory(farmSlug, categorySlug) {
  const farm = getFarm(farmSlug);
  if (!farm) return null;
  return farm.categories.find((c) => c.slug === categorySlug);
}

export function getFarmItem(farmSlug, categorySlug, itemSlug) {
  const cat = getFarmCategory(farmSlug, categorySlug);
  if (!cat) return null;
  return cat.items.find((i) => i.slug === itemSlug);
}

export function getSeasonal(slug) {
  return seasonalFarms.find((s) => s.slug === slug);
}

export function getLimitedEvent(slug) {
  return limitedEvents.find((e) => e.slug === slug);
}
